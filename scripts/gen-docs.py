"""Write docs/rules.md from the rule files, or fail when the committed copy differs."""

import argparse
import sys
from pathlib import Path
from typing import TYPE_CHECKING

from scrubcast.rules.loader import RuleCatalog, load_rules, resolve_plot

if TYPE_CHECKING:
    from scrubcast.models.rules import Parameter, Rule

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/rules.md"
COMMAND = "uv run python scripts/gen-docs.py"


def _value(value: Parameter) -> str:
    """Print a rule value as written in its file; the model stores every number as a float."""
    return value if isinstance(value, str) else f"{value:g}"


def _llccr(numbers: list[int]) -> str:
    return ", ".join(map(str, numbers)) if numbers else "none"


def _citation(section: str, numbers: list[int]) -> str:
    if not numbers:
        return f"Section {section}, no LLCC rule number"
    return f"Section {section}, LLCC rule{'s' if len(numbers) > 1 else ''} {_llccr(numbers)}"


def _rule(rule: Rule) -> list[str]:
    threshold, plot = resolve_plot(rule.plot, rule.proxy, rule.origin)
    rows = [
        f"| `{name}` | {_value(value)} | "
        f"{'Scrubcast' if rule.origin.get(name) == 'scrub' else 'Published rule'} |"
        for name, value in rule.proxy.items()
        if name != "kind"
    ]
    return [
        f"### {rule.title} (`{rule.rule_id}`)",
        "",
        f"{_citation(rule.section, rule.llccr)}. Confidence: {rule.confidence}.",
        "",
        f"> {rule.text}",
        "",
        f"Proxy `{rule.proxy['kind']}` reads: {', '.join(f'`{need}`' for need in rule.needs)}.",
        "",
        "| Parameter | Value | Set by |",
        "| --- | --- | --- |",
        *rows,
        "",
        (
            f"Plotted variable: `{plot.variable}`, threshold `{threshold.comparator}` "
            f"{_value(threshold.value)} {threshold.unit}. "
            f'Readout: "N of M members {plot.readout_phrase}".'
        ),
        "",
        f"Approximation: {rule.approximation_note}",
        "",
    ]


def render(catalog: RuleCatalog) -> str:
    """Render every rule set, vehicle limit and site from the validated catalog."""
    lines = [
        "# Rules",
        "",
        f"Generated by `{COMMAND}` from the JSON files in `rules/`.",
        "Edit those files, then run the command; `make check` fails when this page is out",
        "of date.",
        "",
        'A value set by "Scrubcast" is this project\'s proxy choice, not a number from the',
        "published rule.",
        "",
    ]
    for rule_set in catalog.rule_sets.values():
        lines += [
            f"## {rule_set.rule_set_id}",
            "",
            (
                f"Version `{rule_set.version}`, source dated {rule_set.source_date.isoformat()}: "
                f"<{rule_set.source_url}>"
            ),
            "",
        ]
        for rule in rule_set.rules:
            lines += _rule(rule)
        lines += [
            "### Rules Scrubcast cannot evaluate",
            "",
            "| Rule | LLCC rules | Why |",
            "| --- | --- | --- |",
            *(
                f"| {rule.title} (`{rule.rule_id}`) | {_llccr(rule.llccr)} | {rule.reason} |"
                for rule in rule_set.not_evaluable
            ),
            "",
        ]
    lines += [
        "## Liftoff wind (`liftoff_wind`)",
        "",
        "| Vehicle | Limit | Height above pad | Measure | Readout | Source |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for vehicle in catalog.vehicles.values():
        threshold, plot = resolve_plot(vehicle.plot, vehicle.parameters())
        lines.append(
            f"| {', '.join(vehicle.rocket_names)} | `{threshold.comparator}` "
            f"{_value(threshold.value)} {threshold.unit} | "
            f"{_value(vehicle.reference_height_m)} m | {vehicle.measure} | "
            f"N of M members {plot.readout_phrase} | "
            f"[{vehicle.source_note}]({vehicle.source_url}) |"
        )
    lines += [
        "",
        "Vehicles without a published limit show liftoff wind under the rules Scrubcast",
        "cannot evaluate.",
        "",
        "## Sites",
        "",
        (
            "| Site | Tier | Launch Library locations | Forecast point | METAR station "
            "| Rule sets | Reference only |"
        ),
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for site in catalog.sites.values():
        point = (
            f"{site.forecast_point.latitude}, {site.forecast_point.longitude}"
            if site.forecast_point
            else "the pad"
        )
        locations = ", ".join(map(str, site.location_ids)) or "any other"
        lines.append(
            f"| `{site.site_id}` | {site.tier} | {locations} | {point} | "
            f"{site.metar_station or 'none'} | {', '.join(site.rule_sets)} | "
            f"{'yes' if site.reference_only else 'no'} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write the page, or with --check exit 1 when the committed page is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    text = render(load_rules())
    if not args.check:
        OUTPUT.write_text(text, encoding="utf-8")
        return
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
        sys.exit(
            f"{OUTPUT.relative_to(ROOT)} does not match the rule files. "
            f"Run `{COMMAND}` and commit the result."
        )


if __name__ == "__main__":
    main()
